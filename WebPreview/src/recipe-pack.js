export function mergeEverydayRecipes(state) {
  if ((state.appliedRecipePacks ?? []).includes(PACK_ID)) return state;
  const names = new Set(state.recipes.map(r => r.name.trim()));
  const ids = new Set(state.recipes.map(r => r.id));
  const additions = everydayRecipes.filter(r => !ids.has(r.id) && !names.has(r.name));
  return {...state, recipes:[...state.recipes, ...structuredClone(additions)], appliedRecipePacks:[...(state.appliedRecipePacks ?? []), PACK_ID]};
}
